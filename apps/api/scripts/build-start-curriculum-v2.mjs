/** @param {object} p */
function shell(p) {
  const isChallenge = p.lessonKind === 'challenge';
  return {
    contentKey: p.contentKey,
    title: p.title,
    sortOrder: p.sortOrder,
    lessonType: 'TEXT',
    estimatedMinutes: p.estimatedMinutes ?? (isChallenge ? 18 : 12),
    live: {
      methodology: 'LIVE',
      realLifeContext: p.objectivePt,
      learn: p.coreConcepts.join('; '),
      buildPractice: isChallenge ? 'Revisão cumulativa do módulo.' : 'Prática guiada (Player v2 — em produção).',
      verify: isChallenge ? 'Assessment cumulativo (em produção).' : 'Verify (em produção).',
      executeMission: p.outcomePt,
      curriculum: {
        objectivePt: p.objectivePt,
        outcomePt: p.outcomePt,
        coreConcepts: p.coreConcepts,
        prerequisites: p.prerequisites,
        lessonKind: p.lessonKind ?? 'lesson',
        playerVersionTarget: 2,
      },
    },
  };
}

